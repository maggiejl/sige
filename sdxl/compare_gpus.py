"""Compare the same output image across GPUs (same prompt, seed and code) to measure hardware-induced drift.

    python compare_gpus.py ablation_results          # every machine under ablation_results/

For every pair of machines, prompt and image in <root>/<machine>/baseline/prompt*/512/, computes the PSNR between
the two machines' images. Writes <root>/cross_gpu.csv (one row per prompt, pair and image) and
<root>/cross_gpu.tex (a LaTeX table of the PSNRs, for the report appendix).
"""

import argparse
import csv
import itertools
import os

import numpy as np
from PIL import Image

IMAGES = [  # (file, label in the LaTeX table)
    ("original.png", "Original (generated)"),
    ("r0.10_dense.png", "Dense SDXL edit"),
    ("r0.10_sige_conv.png", "SIGE (conv) edit"),
    ("r0.10_sige_conv_attn.png", "SIGE (conv+attn) edit"),
]
NAMES = {"a100": "A100", "h200": "H200", "rtx5070tilaptop": "RTX 5070 Ti"}


def load(path):
    return np.asarray(Image.open(path).convert("RGB")).astype(np.float64)


def psnr(a, b):
    mse = ((a - b) ** 2).mean()
    return float("inf") if mse == 0 else 10 * np.log10(255.0 ** 2 / mse)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("root", nargs="?", default="ablation_results")
    p.add_argument("--resolution", default="512")
    args = p.parse_args()

    machines = sorted(d for d in os.listdir(args.root) if os.path.isdir(os.path.join(args.root, d, "baseline")))
    prompts = sorted(d for d in os.listdir(os.path.join(args.root, machines[0], "baseline")) if d.startswith("prompt"))
    pairs = list(itertools.combinations(machines, 2))

    rows = []
    for prompt in prompts:
        for fname, _ in IMAGES:
            for a, b in pairs:
                pa = os.path.join(args.root, a, "baseline", prompt, args.resolution, fname)
                pb = os.path.join(args.root, b, "baseline", prompt, args.resolution, fname)
                if not (os.path.exists(pa) and os.path.exists(pb)):
                    continue
                A, B = load(pa), load(pb)
                rows.append(dict(prompt=prompt, image=fname, gpu_a=a, gpu_b=b, psnr=round(psnr(A, B), 2),
                                 max_abs_diff=int(np.abs(A - B).max())))

    out_csv = os.path.join(args.root, "cross_gpu.csv")
    with open(out_csv, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    # LaTeX: rows = image x prompt, columns = GPU pairs, plus a mean row per image
    pair_names = ["%s / %s" % (NAMES.get(a, a), NAMES.get(b, b)) for a, b in pairs]
    lines = [
        "\\begin{table}[h!]", "\\centering", "\\small",
        "\\caption{Cross-GPU agreement: PSNR (dB) between the same image produced on two different GPUs, "
        "with the same code, prompt, seed and starting noise ($%s\\times%s$, 10\\%% edit). Identical images would "
        "give infinite PSNR. Generated by \\texttt{sdxl/compare\\_gpus.py}.}" % (args.resolution, args.resolution),
        "\\label{tab:app_cross_gpu}",
        "\\begin{tabular}{ll" + "r" * len(pairs) + "}", "\\toprule",
        "Image & Prompt & " + " & ".join(pair_names) + " \\\\", "\\midrule",
    ]
    for fname, label in IMAGES:
        sel = [r for r in rows if r["image"] == fname]
        if not sel:
            continue
        for i, prompt in enumerate(prompts):
            vals = []
            for a, b in pairs:
                m = [r["psnr"] for r in sel if r["prompt"] == prompt and r["gpu_a"] == a and r["gpu_b"] == b]
                vals.append("%.1f" % m[0] if m else "--")
            lines.append("%s & %d & %s \\\\" % (label if i == 0 else "", i + 1, " & ".join(vals)))
        means = []
        for a, b in pairs:
            m = [r["psnr"] for r in sel if r["gpu_a"] == a and r["gpu_b"] == b]
            means.append("\\textit{%.1f}" % np.mean(m))
        lines.append(" & \\textit{mean} & %s \\\\" % " & ".join(means))
        lines.append("\\midrule")
    lines[-1] = "\\bottomrule"
    lines += ["\\end{tabular}", "\\end{table}"]
    out_tex = os.path.join(args.root, "cross_gpu.tex")
    with open(out_tex, "w") as f:
        f.write("\n".join(lines) + "\n")

    for fname, label in IMAGES:
        v = [r["psnr"] for r in rows if r["image"] == fname]
        if v:
            print("%-24s PSNR across GPUs: %.1f-%.1f dB (mean %.1f)" % (label, min(v), max(v), np.mean(v)))
    print("Wrote", out_csv, "and", out_tex)


if __name__ == "__main__":
    main()
